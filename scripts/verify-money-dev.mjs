/** Explicitly opt-in, disposable DEV-only ARS-89 integration journey.
 * Never accepts a production target or a real user's credentials. Writes only
 * this run's synthetic space; keeps its disposable login in ignored tmp for
 * the paired native journey. No provider, email, custody or real-money calls.
 */
import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { ConvexHttpClient } from "convex/browser";

const target = "https://rosy-mink-170.eu-west-1.convex.cloud";
if (process.env.NUMA_DEV_MONEY_QA !== "1") throw new Error("Set NUMA_DEV_MONEY_QA=1 to authorize disposable DEV records.");
if (process.env.CONVEX_URL && process.env.CONVEX_URL !== target) throw new Error("This verifier only accepts Numa DEV.");
const output = new URL("../tmp/numa-pro-goal/", import.meta.url);
await mkdir(output, { recursive: true });
const client = new ConvexHttpClient(target);
const flags = await client.query("authConfig:flags", {});
if (flags.emailVerification) throw new Error("DEV signup would send an email; this verifier does not authorize provider use.");
const key = (operation) => `ars89-${operation}-${randomUUID()}`;
const email = `numa-ars89-${Date.now()}@example.test`;
const password = `Q7!${randomBytes(24).toString("base64url")}b`;
const auth = await client.action("auth:signIn", { provider: "password", params: { flow: "signUp", email, password, name: "Disposable Money QA" } });
assert.ok(auth.tokens?.token, "Disposable DEV signup must return a session without email");
client.setAuth(auth.tokens.token);
await writeFile(new URL("dev-qa-session.json", output), JSON.stringify({ target, email, password, token: auth.tokens.token }, null, 2), { mode: 0o600 });
const checks = [];
function pass(name) { checks.push(name); console.log(`PASS ${name}`); }
const space = await client.mutation("spaces:create", { name: "ARS-89 disposable money QA", spaceKind: "personal", currency: "EUR", clientMutationId: key("space") });
const portfolioId = space.id;
const snapshot = () => client.query("mobile:portfolioSnapshot", { portfolioId });
let current = await snapshot();
const accountA = current.assets[0].id;
await client.mutation("mobile:upsertAsset", { id: accountA, portfolioId, name: "QA Operating", kind: "cash", balance: 1000, currency: "EUR", clientMutationId: key("opening") });
const accountB = (await client.mutation("mobile:upsertAsset", { portfolioId, name: "QA Reserve", kind: "cash", balance: 500, currency: "EUR", clientMutationId: key("reserve") })).id;
const categoryId = (await client.mutation("mobile:createCategory", { portfolioId, name: "QA Studio costs", kind: "expense", monthlyLimit: 100, clientMutationId: key("category") })).id;
const balance = (state, id) => state.assets.find(row => row.id === id).balance;
const recordedAt = Date.now() - 1000;
const incomeArgs = { portfolioId, description: "QA Unlinked income", kind: "income", amount: 250, currency: "EUR", occurredAt: recordedAt, clientMutationId: key("income") };
const [income, incomeReplay] = await Promise.all([client.mutation("mobile:createTransaction", incomeArgs), client.mutation("mobile:createTransaction", incomeArgs)]);
assert.equal(income.id, incomeReplay.id);
current = await snapshot();
assert.equal(current.transactions.filter(row => row.id === income.id).length, 1);
assert.equal(balance(current, accountA), 1000);
assert.equal(balance(current, accountB), 500);
pass("Concurrent same-intent income deduplicates; explicit unlinked leaves cash untouched");
const expense = await client.mutation("mobile:createTransaction", { portfolioId, description: "QA Linked expense", kind: "expense", amount: 12.34, currency: "EUR", occurredAt: recordedAt, categoryId, accountId: accountA, clientMutationId: key("expense") });
assert.equal(balance(await snapshot(), accountA), 987.66);
await client.mutation("mobile:updateTransaction", { id: expense.id, amount: 20, accountId: null, clientMutationId: key("unlink") });
current = await snapshot();
assert.equal(balance(current, accountA), 1000);
assert.equal(current.transactions.find(row => row.id === expense.id).accountId, null);
pass("Edit clears an account explicitly and undoes only the previous linked cash effect");
const transferArgs = { portfolioId, fromAccountId: accountA, toAccountId: accountB, amount: 125.25, currency: "EUR", occurredAt: recordedAt, description: "QA Reserve transfer", sourceEventId: key("source"), clientMutationId: key("transfer") };
const [transfer, transferReplay] = await Promise.all([client.mutation("money:createTransfer", transferArgs), client.mutation("money:createTransfer", transferArgs)]);
assert.equal(transfer.id, transferReplay.id);
current = await snapshot();
assert.equal(balance(current, accountA), 874.75);
assert.equal(balance(current, accountB), 625.25);
assert.equal(current.transfers.length, 1);
assert.equal(current.transactions.length, 2);
const flowBefore = current.dashboard.monthCashflow;
await client.mutation("money:updateTransfer", { id: transfer.id, amount: 200, clientMutationId: key("correct-transfer") });
current = await snapshot();
assert.equal(balance(current, accountA), 800);
assert.equal(balance(current, accountB), 700);
assert.equal(current.dashboard.monthCashflow, flowBefore);
pass("Transfer creates and corrects both legs atomically without income, expense or cashflow mirroring");
await assert.rejects(client.mutation("money:updateTransfer", { id: transfer.id, toAccountId: accountA, clientMutationId: key("invalid-transfer") }));
current = await snapshot();
assert.equal(balance(current, accountA), 800);
assert.equal(balance(current, accountB), 700);
const deleteArgs = { id: transfer.id, clientMutationId: key("delete-transfer") };
await client.mutation("money:deleteTransfer", deleteArgs);
assert.equal((await client.mutation("money:deleteTransfer", deleteArgs)).replayed, true);
const sourceReplay = await client.mutation("money:createTransfer", { ...transferArgs, clientMutationId: key("source-replay") });
assert.equal(sourceReplay.id, transfer.id);
current = await snapshot();
assert.equal(current.transfers.length, 0);
assert.equal(balance(current, accountA), 1000);
assert.equal(balance(current, accountB), 500);
pass("Invalid transfer leaves both legs unchanged; deleted transport/source replay cannot recreate money");
const deleteExpense = { id: expense.id, clientMutationId: key("delete-expense") };
await client.mutation("mobile:deleteTransaction", deleteExpense);
assert.equal((await client.mutation("mobile:deleteTransaction", deleteExpense)).replayed, true);
assert.equal(balance(await snapshot(), accountA), 1000);
pass("Deleted transaction acknowledgement can be replayed after snapshot removal");
await client.mutation("money:setCategoryBudget", { categoryId, monthlyLimit: 150, clientMutationId: key("budget") });
await client.mutation("portfolios:update", { id: portfolioId, patch: { defaultCurrency: "USD" }, clientMutationId: key("default-usd") });
current = await snapshot();
assert.equal(current.portfolio.defaultCurrency, "USD");
assert.equal(current.categories.find(row => row.id === categoryId).budgetCurrency, "EUR");
assert.equal(current.categories.find(row => row.id === categoryId).monthlyLimit, 150);
pass("Existing budget keeps EUR denomination after space default changes to USD");
const anonymous = new ConvexHttpClient(target);
await assert.rejects(anonymous.query("mobile:portfolioSnapshot", { portfolioId }));
await assert.rejects(anonymous.mutation("money:setCategoryBudget", { categoryId, monthlyLimit: 1, clientMutationId: key("anonymous") }));
pass("Unauthenticated snapshot and financial write fail closed");
// Return default to EUR for the explicitly paired, still-disposable native journey.
await client.mutation("portfolios:update", { id: portfolioId, patch: { defaultCurrency: "EUR" }, clientMutationId: key("default-eur") });
await writeFile(new URL("dev-money-evidence.json", output), JSON.stringify({ target, checkedAt: new Date().toISOString(), portfolioId, accountA, accountB, categoryId, checks, status: "passed", limitation: "Live backend transport and reconciliation; not native UI persistence or adversarial concurrency proof" }, null, 2));
console.log(`PASS ${checks.length} live DEV integration checks. Disposable session stored privately; no credentials printed.`);
